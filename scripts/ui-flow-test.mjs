await o.getByLabel('Latitude').fill('-7.7650'); await o.getByLabel('Longitude').fill('110.3800');
await o.getByText('Any time (24/7)').click();
await o.getByRole('button', { name: 'Publish listing' }).click();
await o.waitForURL(/\/vehicles\/\d+$/); const vid = o.url().split('/').pop(); step('bicycle published via UI → /vehicles/'+vid);
