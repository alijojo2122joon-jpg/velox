await r.goto(B+'/register');
await r.fill('input[autocomplete=name]', 'UI Renter');
await r.fill('input[type=email]', `uirenter${s}@test.id`);
await r.fill('input[type=tel]', `0816${s}22`);
await r.fill('input[type=password]', 'secret123');
await r.click('button[type=submit]'); await r.waitForURL('**/search'); step('renter registered → search');
