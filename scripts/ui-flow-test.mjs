const step = (m) => console.log('  ✓', m);
// Owner registers and lists a bike via the UI
const o = await mk();
await o.goto(B+'/register?role=owner'); 
await o.fill('input[autocomplete=name]', 'UI Owner');
await o.fill('input[type=email]', `uiowner${s}@test.id`);
await o.fill('input[type=tel]', `0815${s}11`);
await o.fill('input[type=password]', 'secret123');
await o.click('button[type=submit]');
await o.waitForURL('**/vehicles/new'); step('owner registered → listing form');
await o.fill('input[maxlength="80"]', `UI Flow Bike ${s}`);
await o.fill('input[placeholder="Polygon, Honda…"]', 'Polygon');
const inputs = o.locator('section, div').filter({ hasText: 'Model' });
await o.getByLabel('Model').fill('Heist');
await o.setInputFiles('input[type=file][multiple]', new URL('./fixtures/bike.png', import.meta.url).pathname);
