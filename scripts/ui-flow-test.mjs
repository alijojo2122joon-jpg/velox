await r.getByText(`UI Flow Bike ${s}`).first().click(); await r.waitForURL('**/vehicles/'+vid); step('found the new bike by location search');
const widget = r.locator('.sticky');
await widget.getByText('Available for these times').waitFor({ timeout: 8000 });
await widget.locator('input[type=checkbox]').check();
await widget.getByRole('button', { name: 'Request to book' }).click();
await r.waitForURL(/\/bookings\/\d+$/); const bid = r.url().split('/').pop(); step('booking requested → /bookings/'+bid);
